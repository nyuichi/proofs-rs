import {readFileSync,writeFileSync} from 'node:fs';
const base=new URL('../content/tool-docs/',import.meta.url);
const manifest=JSON.parse(readFileSync(new URL('manifest.json',base),'utf8'));
const docs={};
for(const [id,revisions] of Object.entries(manifest)) {
 if(!revisions.length)throw Error('Empty document: '+id);
 docs[id]=revisions.map((r,i)=>{
  if(r.revision!==i+1 || !r.summary || !/^\d{4}-\d{2}-\d{2}$/.test(r.date) || !/^[a-z0-9-]+\/\d+\.md$/.test(r.file))throw Error('Invalid revision: '+id);
  const markdown=readFileSync(new URL(r.file,base),'utf8').trim();
  if(!markdown)throw Error('Empty content: '+id);
  return {revision:r.revision,date:r.date,summary:r.summary,markdown};
 });
}
const output='// Generated by scripts/build-tool-docs.mjs; edit content/tool-docs instead.\nexport const documents: Record<string, {revision:number;date:string;summary:string;markdown:string}[]> = '+JSON.stringify(docs,null,2)+';\n';
const path=new URL('../src/tool-doc-content.ts',import.meta.url);
if(process.argv.includes('--check')){if(readFileSync(path,'utf8')!==output)throw Error('Run node scripts/build-tool-docs.mjs');}
else writeFileSync(path,output);
